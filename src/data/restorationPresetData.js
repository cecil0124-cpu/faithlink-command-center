function getUpcomingSunday() {
  const date = new Date()
  const day = date.getDay()
  const daysUntilSunday = day === 0 ? 0 : 7 - day
  date.setDate(date.getDate() + daysUntilSunday)
  return date.toISOString().slice(0, 10)
}

